// ===== إحصائيات المكتبة =====
export function getAnalysisStats(): {
  detailedArticles: number;
  perLaw: Record<LawType, number>;
  totalArticlesInStore: number;
} {
  const perLaw: Record<string, number> = {
    penal: 0,
    criminal_proc: 0,
    civil: 0,
    civil_proc: 0,
    personal: 0,
  };

  for (const key of Object.keys(ALL_ANALYSIS)) {
    const law = key.split('-')[0] as LawType;
    if (law in perLaw) {
      perLaw[law]++;
    }
  }

  let totalInStore = 0;
  for (const key of Object.keys(ARTICLE_TEXT_DB)) {
    totalInStore++;
  }

  return {
    detailedArticles: Object.keys(ALL_ANALYSIS).length,
    perLaw: perLaw as Record<LawType, number>,
    totalArticlesInStore: totalInStore,
  };
}
