// ===== تصنيف المواد حسب رقمها ونوع القانون =====
function categorizeArticle(law: LawType, num: number): ArticleCategory {
  if (law === 'penal') {
    if (num <= 18) return 'penalties';
    if (num >= 19 && num <= 29) return 'jurisdiction';
    if (num >= 30 && num <= 49) return 'general_provision';
    if (num >= 86 && num <= 102) return 'public_order';
    if (num >= 103 && num <= 112) return 'bribery';
    if (num >= 112 && num <= 119) return 'embezzlement';
    if (num >= 120 && num <= 132) return 'public_order';
    if (num >= 126 && num <= 129) return 'torture';
    if (num >= 133 && num <= 157) return 'insult_defamation';
    if (num >= 160 && num <= 166) return 'protection';
    if (num >= 167 && num <= 170) return 'transport';
    if (num >= 171 && num <= 189) return 'incitement';
    if (num >= 190 && num <= 229) return 'public_order';
    if (num >= 230 && num <= 239) return 'murder';
    if (num >= 240 && num <= 248) return 'assault';
    if (num >= 250 && num <= 259) return 'protection';
    if (num >= 260 && num <= 266) return 'kidnapping';
    if (num >= 267 && num <= 293) return 'sexual_offenses';
    if (num >= 294 && num <= 312) return 'insult_defamation';
    if (num >= 312 && num <= 330) return 'protection';
    if (num >= 331 && num <= 343) return 'theft';
    if (num >= 344 && num <= 360) return 'fraud';
    if (num >= 361 && num <= 381) return 'checks';
    if (num >= 382 && num <= 400) return 'fraud';
    if (num >= 400 && num <= 430) return 'forgery';
    if (num >= 430 && num <= 440) return 'breach_of_trust';
    if (num >= 500 && num <= 536) return 'checks';
    return 'general_provision';
  }

  if (law === 'criminal_proc') {
    if (num <= 50) return 'jurisdiction';
    if (num >= 51 && num <= 99) return 'procedure';
    if (num >= 100 && num <= 219) return 'investigation';
    if (num >= 220 && num <= 339) return 'trial';
    if (num >= 340 && num <= 433) return 'appeal';
    if (num >= 434 && num <= 470) return 'appeal';
    if (num >= 470) return 'execution';
    return 'procedure';
  }

  if (law === 'civil') {
    if (num <= 20) return 'general_provision';
    if (num >= 21 && num <= 83) return 'contract';
    if (num >= 84 && num <= 195) return 'obligations';
    if (num >= 163 && num <= 185) return 'civil_liability';
    if (num >= 196 && num <= 340) return 'obligations';
    if (num >= 341 && num <= 425) return 'obligations';
    if (num >= 426 && num <= 500) return 'evidence';
    if (num >= 500 && num <= 800) return 'property';
    if (num >= 800) return 'property';
    return 'general_provision';
  }

  if (law === 'civil_proc') {
    if (num <= 80) return 'jurisdiction';
    if (num >= 81 && num <= 150) return 'procedure';
    if (num >= 151 && num <= 240) return 'evidence';
    if (num >= 241 && num <= 268) return 'appeal';
    if (num >= 269 && num <= 300) return 'appeal';
    if (num >= 301) return 'execution';
    return 'procedure';
  }

  if (law === 'personal') {
    if (num <= 10) return 'marriage';
    if (num >= 11 && num <= 14) return 'divorce';
    if (num >= 15 && num <= 19) return 'custody';
    if (num >= 20 && num <= 30) return 'inheritance';
    if (num >= 31 && num <= 40) return 'alimony';
    return 'general_provision';
  }

  return 'general_provision';
}

